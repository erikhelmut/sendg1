"""MDP terms for the beam-walking task.

Every term here reads one thing: the beam centreline that
:class:`~sendg1.common.beam.terrain.BeamPathTerrainCfg` exports through the
terrain's ``flat_patches``. Positions are projected onto that polyline: the
base, for its offset from the beam, and each foot, for progress. All of it is
ground truth, so it feeds rewards, terminations, the curriculum and the critic
-- never the actor.

Progress is the furthest point where a foot has LANDED on the beam: in contact,
at the beam's top surface, laterally over it. An earlier version used the base
position, which credited ground covered while toppling -- a robot that never
acted scored 8.5% of the beam at every width, just by falling forward off the
platform.

Per-episode state (the furthest point reached) lives in one :class:`BeamTracker`
per env instance. It is updated at most once per env step and archived then
cleared by the ``reset_beam_tracker`` event.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING

import torch

from sendg1.common.beam.terrain import BEAM_PATH_PATCH, BeamPathTerrainCfg, beam_width
from sendg1.common.robots.g1 import G1_FOOT_SITES

if TYPE_CHECKING:
  from mjlab.envs import ManagerBasedRlEnv

SUCCESS_FRAC = 0.95
"""Fraction of the beam that counts as crossing it."""

FALL_MARGIN = 0.35
"""A base lower than this above the beam top has left the beam. Standing, the
G1 pelvis sits ~0.79 m above its support; a deep crouch stays well above 0.35."""

FOOT_CONTACT_SENSOR = "feet_ground_contact"
"""Per-foot terrain contact (``sendg1.common.sensors``). Its primaries are the left
then the right ankle, the same order as ``G1_FOOT_SITES``."""

FOOT_HEIGHT_TOL = 0.05
"""A foot is on the beam when its sole site is within this of the beam top.
Standing, the site sits at -0.003 m; contact with the pit floor or the side of
the beam is far lower."""

FOOT_LATERAL_TOL = 0.035
"""Half the G1 sole width: a foot centred this far past the beam edge still has
sole on the beam."""


@dataclass
class PathProjection:
  arc: torch.Tensor
  """[B] arc length from the path start to the closest point (m)."""
  lateral: torch.Tensor
  """[B] signed distance from the centreline, positive left of travel (m)."""
  tangent_yaw: torch.Tensor
  """[B] world yaw of the closest path segment (rad)."""
  length: torch.Tensor
  """[B] total path length (m)."""


def project_onto_path(points_xy: torch.Tensor, xy: torch.Tensor) -> PathProjection:
  """Project positions ``xy`` [B, 2] onto per-env polylines ``points_xy`` [B, N, 2]."""
  a = points_xy[:, :-1]
  ab = points_xy[:, 1:] - a
  seg_len2 = torch.sum(ab * ab, dim=-1).clamp_min(1e-12)
  rel = xy[:, None, :] - a
  t = (torch.sum(rel * ab, dim=-1) / seg_len2).clamp(0.0, 1.0)
  offset = rel - t[..., None] * ab
  dist2 = torch.sum(offset * offset, dim=-1)
  idx = torch.argmin(dist2, dim=1)

  rows = torch.arange(xy.shape[0], device=xy.device)
  seg_len = torch.sqrt(seg_len2)
  seg_start = torch.cumsum(seg_len, dim=1) - seg_len
  ab_i = ab[rows, idx]
  rel_i = rel[rows, idx]
  cross = ab_i[:, 0] * rel_i[:, 1] - ab_i[:, 1] * rel_i[:, 0]
  return PathProjection(
    arc=seg_start[rows, idx] + t[rows, idx] * seg_len[rows, idx],
    lateral=torch.sign(cross) * torch.sqrt(dist2[rows, idx]),
    tangent_yaw=torch.atan2(ab_i[:, 1], ab_i[:, 0]),
    length=seg_len.sum(dim=1),
  )


@dataclass
class BeamState:
  proj: PathProjection
  width: torch.Tensor
  """[B] beam width at the env's curriculum level (m)."""
  frac: torch.Tensor
  """[B] fraction of the beam up to the base's closest point, in [0, 1]."""
  top_z: torch.Tensor
  """[B] world height of the beam top (m)."""
  path_xy: torch.Tensor
  """[B, N, 2] the env's beam centreline in world xy."""


class BeamTracker:
  """Beam geometry lookup plus the per-episode progress record."""

  _ATTR = "_sendg1_beam_tracker"

  def __init__(self, env: ManagerBasedRlEnv) -> None:
    terrain = env.scene.terrain
    if terrain is None or BEAM_PATH_PATCH not in terrain.flat_patches:
      raise RuntimeError("beam MDP terms need terrain generated by BeamPathTerrainCfg")
    gen = terrain.cfg.terrain_generator
    assert gen is not None and terrain.terrain_origins is not None
    if not gen.curriculum:
      # Width is looked up from the row index, which equals difficulty only when
      # rows are laid out as a curriculum.
      raise RuntimeError("beam terrain must be generated with curriculum=True")
    cfgs = list(gen.sub_terrains.values())
    if not all(isinstance(c, BeamPathTerrainCfg) for c in cfgs):
      raise RuntimeError("every sub-terrain of a beam task must be a BeamPathTerrainCfg")
    ref = cfgs[0]
    for c in cfgs[1:]:
      for name in ("width_range", "platform_size", "beam_height"):
        if getattr(c, name) != getattr(ref, name):
          raise ValueError(f"beam columns disagree on {name!r}")

    self._env = env
    self._terrain = terrain
    self._robot = env.scene["robot"]
    self._contact = env.scene[FOOT_CONTACT_SENSOR]
    self._foot_site_ids, _ = self._robot.find_sites(G1_FOOT_SITES, preserve_order=True)
    self.platform_half = ref.platform_size / 2

    num_rows = terrain.terrain_origins.shape[0]
    lo, hi = gen.difficulty_range
    self.row_widths = torch.tensor(
      [
        beam_width(lo + (hi - lo) * r / max(num_rows - 1, 1), *ref.width_range)
        for r in range(num_rows)
      ],
      device=env.device,
      dtype=torch.float32,
    )

    n = env.num_envs
    self.max_frac = torch.zeros(n, device=env.device)
    """Furthest fraction of the beam where a foot has landed this episode."""
    self.last_frac = torch.zeros(n, device=env.device)
    """``max_frac`` of each env's previous, completed episode."""
    self.delta_m = torch.zeros(n, device=env.device)
    """New ground covered in the latest update (m)."""
    self.succeeded = torch.zeros(n, device=env.device, dtype=torch.bool)
    """Covered ``SUCCESS_FRAC`` of the beam at some point this episode."""
    self.new_success = torch.zeros_like(self.succeeded)
    """Crossed ``SUCCESS_FRAC`` for the first time in the latest update."""
    self.last_success = torch.zeros_like(self.succeeded)
    """``succeeded`` of each env's previous, completed episode."""
    self._stamp = -1

  @classmethod
  def get(cls, env: ManagerBasedRlEnv) -> BeamTracker:
    tracker = getattr(env, cls._ATTR, None)
    if tracker is None:
      tracker = cls(env)
      setattr(env, cls._ATTR, tracker)
    return tracker

  def state(self) -> BeamState:
    terrain = self._terrain
    path = terrain.flat_patches[BEAM_PATH_PATCH][
      terrain.terrain_levels, terrain.terrain_types
    ]
    pos = self._robot.data.root_link_pos_w
    proj = project_onto_path(path[..., :2], pos[:, :2])
    width = self.row_widths[terrain.terrain_levels]
    beam_len = (proj.length - self.platform_half).clamp_min(1e-6)
    frac = ((proj.arc - self.platform_half) / beam_len).clamp(0.0, 1.0)
    return BeamState(
      proj=proj, width=width, frac=frac, top_z=path[:, 0, 2], path_xy=path[..., :2]
    )

  def foothold_frac(self, st: BeamState) -> torch.Tensor:
    """[B] furthest beam fraction under a foot that is on the beam right now."""
    feet = self._robot.data.site_pos_w[:, self._foot_site_ids]  # [B, F, 3]
    b, f = feet.shape[:2]
    proj = project_onto_path(
      st.path_xy.repeat_interleave(f, dim=0), feet[..., :2].reshape(b * f, 2)
    )
    beam_len = (proj.length - self.platform_half).clamp_min(1e-6)
    frac = ((proj.arc - self.platform_half) / beam_len).clamp(0.0, 1.0).view(b, f)
    on_beam = (
      (self._contact.data.found.view(b, f) > 0)
      & ((feet[..., 2] - st.top_z[:, None]).abs() <= FOOT_HEIGHT_TOL)
      & (proj.lateral.view(b, f).abs() <= 0.5 * st.width[:, None] + FOOT_LATERAL_TOL)
    )
    return torch.where(on_beam, frac, torch.zeros_like(frac)).amax(dim=1)

  def update(self) -> None:
    """Advance the progress record. Idempotent within one env step."""
    stamp = self._env.common_step_counter
    if stamp == self._stamp:
      return
    self._stamp = stamp
    st = self.state()
    new_max = torch.maximum(self.max_frac, self.foothold_frac(st))
    self.delta_m = (new_max - self.max_frac) * (st.proj.length - self.platform_half)
    self.max_frac = new_max
    reached = new_max >= SUCCESS_FRAC
    self.new_success = reached & ~self.succeeded
    self.succeeded = self.succeeded | reached

  def reset(self, env_ids: torch.Tensor | slice) -> None:
    self.last_frac[env_ids] = self.max_frac[env_ids]
    self.last_success[env_ids] = self.succeeded[env_ids]
    self.max_frac[env_ids] = 0.0
    self.delta_m[env_ids] = 0.0
    self.succeeded[env_ids] = False
    self.new_success[env_ids] = False


# ---------------------------------------------------------------------------
# Events
# ---------------------------------------------------------------------------


def reset_beam_tracker(env: ManagerBasedRlEnv, env_ids: torch.Tensor | None) -> None:
  """Event (mode="reset"): archive and clear the finished episode's progress.

  Ordering is safe: mjlab's ``_reset_idx`` computes the curriculum, which reads
  ``max_frac``, before it applies reset events.
  """
  BeamTracker.get(env).reset(slice(None) if env_ids is None else env_ids)


# ---------------------------------------------------------------------------
# Rewards
# ---------------------------------------------------------------------------


def beam_progress(env: ManagerBasedRlEnv, max_speed: float = 0.6) -> torch.Tensor:
  """New furthest foothold along the beam, as a speed normalised to [0, 1].

  Only a new furthest foothold pays, so walking back and forth earns nothing and
  pausing to test the footing costs nothing but time. The ``max_speed`` cap
  removes any incentive to rush.
  """
  tracker = BeamTracker.get(env)
  tracker.update()
  speed = tracker.delta_m / env.step_dt
  return speed.clamp(0.0, max_speed) / max_speed


def beam_success_bonus(env: ManagerBasedRlEnv) -> torch.Tensor:
  """One-off bonus on the step the robot first covers ``SUCCESS_FRAC`` of the beam.

  Divided by ``step_dt`` because the reward manager multiplies every term by it,
  so the term's weight is the bonus itself.
  """
  tracker = BeamTracker.get(env)
  tracker.update()
  return tracker.new_success.float() / env.step_dt


def base_height_shortfall(env: ManagerBasedRlEnv, target: float = 0.70) -> torch.Tensor:
  """Squared distance the base sits below ``target`` above the beam top (m^2).

  Zero at or above the target. Capped where ``fell_off_beam`` fires, so the few
  steps of a fall add a bounded cost rather than an arbitrarily large one.
  """
  st = BeamTracker.get(env).state()
  height = env.scene["robot"].data.root_link_pos_w[:, 2] - st.top_z
  return torch.square((target - height).clamp(0.0, target - FALL_MARGIN))


def beam_centreline(env: ManagerBasedRlEnv) -> torch.Tensor:
  """Shaping toward the centreline, scaled to the current beam width."""
  st = BeamTracker.get(env).state()
  return torch.exp(-torch.square(st.proj.lateral / (0.5 * st.width)))


# ---------------------------------------------------------------------------
# Terminations
# ---------------------------------------------------------------------------


def fell_off_beam(env: ManagerBasedRlEnv, margin: float = FALL_MARGIN) -> torch.Tensor:
  st = BeamTracker.get(env).state()
  return env.scene["robot"].data.root_link_pos_w[:, 2] < st.top_z + margin


# ---------------------------------------------------------------------------
# Curriculum
# ---------------------------------------------------------------------------


def beam_levels(
  env: ManagerBasedRlEnv,
  env_ids: torch.Tensor | None,
  promote_frac: float = 0.8,
  demote_frac: float = 0.3,
) -> dict[str, torch.Tensor]:
  """Per-env width curriculum: narrower after crossing, wider after failing.

  An env that covered at least ``promote_frac`` of its beam moves one row
  narrower; one that covered less than ``demote_frac`` -- fell early or never
  left the platform -- moves one row wider. mjlab re-samples a random row for
  envs that pass the narrowest, which keeps wide beams in the training mix.
  """
  terrain = env.scene.terrain
  assert terrain is not None and terrain.cfg.terrain_generator is not None
  tracker = BeamTracker.get(env)
  if env_ids is None:
    env_ids = torch.arange(env.num_envs, device=env.device)

  frac = tracker.max_frac[env_ids]
  move_up = frac >= promote_frac
  move_down = (frac < demote_frac) & ~move_up
  # The initial reset happens before any step; there is no episode to judge.
  if env.common_step_counter == 0:
    move_up = torch.zeros_like(move_up)
    move_down = torch.zeros_like(move_down)
  terrain.update_env_origins(env_ids, move_up, move_down)

  levels = terrain.terrain_levels.float()
  result: dict[str, torch.Tensor] = {"mean": levels.mean(), "max": levels.max()}
  if frac.numel() > 0:
    result["episode_progress"] = frac.mean()
    result["episode_success"] = tracker.succeeded[env_ids].float().mean()
  for i, name in enumerate(terrain.cfg.terrain_generator.sub_terrains):
    mask = terrain.terrain_types == i
    if mask.any():
      result[name] = levels[mask].mean()
  return result


# ---------------------------------------------------------------------------
# Privileged observations (critic only; see sendg1.common.obs.terms)
# ---------------------------------------------------------------------------


def beam_progress_obs(env: ManagerBasedRlEnv) -> torch.Tensor:
  return BeamTracker.get(env).state().frac[:, None]


def beam_lateral_offset(env: ManagerBasedRlEnv) -> torch.Tensor:
  return BeamTracker.get(env).state().proj.lateral[:, None]


def beam_heading_error(env: ManagerBasedRlEnv) -> torch.Tensor:
  st = BeamTracker.get(env).state()
  err = st.proj.tangent_yaw - env.scene["robot"].data.heading_w
  return torch.stack([torch.sin(err), torch.cos(err)], dim=-1)


def beam_width_obs(env: ManagerBasedRlEnv) -> torch.Tensor:
  return BeamTracker.get(env).state().width[:, None]
