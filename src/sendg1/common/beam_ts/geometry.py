"""Per-env beam lookup and projection onto the beam centreline.

Every MDP term asks the same questions -- how far along the beam is this point,
how far off the centreline, which way does the beam run here, how wide is it,
where is its top -- and answers them through :class:`BeamGeometry`, which reads
the terrain's exported path (see ``terrain.py``) for the tile each env is on.

Nothing here assumes the beam is straight: points are projected onto a
polyline. Ground truth only; reaches rewards, terminations, the curriculum and
privileged observations, never the student.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING

import torch

from sendg1.common.beam_ts.terrain import BEAM_ENDS_PATCH, BEAM_PATH_PATCH, BeamTileCfg

if TYPE_CHECKING:
  from mjlab.envs import ManagerBasedRlEnv


@dataclass
class Projection:
  """Projection of [B, K] points onto each env's centreline."""

  arc: torch.Tensor
  """[B, K] arc length from the path start (start platform back edge) (m)."""
  lateral: torch.Tensor
  """[B, K] signed distance from the centreline, positive to the left (m)."""
  tangent_yaw: torch.Tensor
  """[B, K] world yaw of the path at the closest point (rad)."""


def project_points(path_xy: torch.Tensor, pts: torch.Tensor) -> Projection:
  """Project ``pts`` [B, K, 2] onto polylines ``path_xy`` [B, N, 2]."""
  a = path_xy[:, None, :-1]  # [B, 1, S, 2]
  ab = path_xy[:, None, 1:] - a
  seg_len2 = (ab * ab).sum(-1).clamp_min(1e-12)  # [B, 1, S]
  rel = pts[:, :, None, :] - a  # [B, K, S, 2]
  t = ((rel * ab).sum(-1) / seg_len2).clamp(0.0, 1.0)
  off = rel - t[..., None] * ab
  d2 = (off * off).sum(-1)  # [B, K, S]
  idx = d2.argmin(-1)  # [B, K]

  seg_len = seg_len2.sqrt()  # [B, 1, S]
  seg_start = seg_len.cumsum(-1) - seg_len
  gather = lambda x: torch.gather(x.expand(*d2.shape), -1, idx[..., None]).squeeze(-1)  # noqa: E731
  t_i = torch.gather(t, -1, idx[..., None]).squeeze(-1)
  ab_i = torch.gather(ab.expand(*d2.shape, 2), 2, idx[..., None, None].expand(*idx.shape, 1, 2)).squeeze(2)
  rel_i = torch.gather(rel, 2, idx[..., None, None].expand(*idx.shape, 1, 2)).squeeze(2)
  cross = ab_i[..., 0] * rel_i[..., 1] - ab_i[..., 1] * rel_i[..., 0]
  return Projection(
    arc=gather(seg_start) + t_i * gather(seg_len),
    lateral=torch.sign(cross) * torch.gather(d2, -1, idx[..., None]).squeeze(-1).sqrt(),
    tangent_yaw=torch.atan2(ab_i[..., 1], ab_i[..., 0]),
  )


class BeamGeometry:
  """Static beam geometry of every tile, indexed per env on demand."""

  _ATTR = "_sendg1_beam_ts_geometry"

  def __init__(self, env: ManagerBasedRlEnv) -> None:
    terrain = env.scene.terrain
    if terrain is None or BEAM_PATH_PATCH not in terrain.flat_patches:
      raise RuntimeError("beam_ts terms need terrain generated by BeamTileCfg")
    gen = terrain.cfg.terrain_generator
    assert gen is not None
    if not gen.curriculum:
      raise RuntimeError("beam_ts terrain must be generated with curriculum=True")
    cfgs = list(gen.sub_terrains.values())
    if not all(isinstance(c, BeamTileCfg) for c in cfgs):
      raise RuntimeError("every sub-terrain must be a BeamTileCfg")
    ref: BeamTileCfg = cfgs[0]  # type: ignore[assignment]
    for c in cfgs[1:]:
      if c.widths != ref.widths:  # type: ignore[attr-defined]
        raise ValueError("beam columns disagree on widths")

    self._terrain = terrain
    dev = env.device
    self.widths = torch.tensor(ref.widths, device=dev, dtype=torch.float32)
    self.num_levels = len(ref.widths)
    self.platform_length = ref.platform_length
    self.platform_width = ref.platform_width
    paths = terrain.flat_patches[BEAM_PATH_PATCH]  # [R, C, N, 3]
    ends = terrain.flat_patches[BEAM_ENDS_PATCH]  # [R, C, 2, 3]
    self._paths = paths
    # Arc length of the beam start / end along each tile's path.
    r, c, n, _ = paths.shape
    flat_paths = paths.reshape(r * c, n, 3)[..., :2]
    flat_ends = ends.reshape(r * c, 2, 3)[..., :2]
    proj = project_points(flat_paths, flat_ends)
    self._beam_arc = proj.arc.reshape(r, c, 2)
    seg = (flat_paths[:, 1:] - flat_paths[:, :-1]).norm(dim=-1).sum(-1)
    self._path_len = seg.reshape(r, c)

  @classmethod
  def get(cls, env: ManagerBasedRlEnv) -> BeamGeometry:
    geo = getattr(env, cls._ATTR, None)
    if geo is None:
      geo = cls(env)
      setattr(env, cls._ATTR, geo)
    return geo

  # -- per-env lookups -------------------------------------------------------

  @property
  def levels(self) -> torch.Tensor:
    return self._terrain.terrain_levels

  @property
  def types(self) -> torch.Tensor:
    return self._terrain.terrain_types

  def path(self) -> torch.Tensor:
    """[B, N, 3] each env's centreline (world), at the top surface height."""
    return self._paths[self.levels, self.types]

  def width(self) -> torch.Tensor:
    """[B] beam width (m)."""
    return self.widths[self.levels]

  def top_z(self) -> torch.Tensor:
    """[B] world height of the beam and platform tops."""
    return self._paths[self.levels, self.types, 0, 2]

  def beam_arc(self) -> torch.Tensor:
    """[B, 2] arc length where the beam proper starts and ends."""
    return self._beam_arc[self.levels, self.types]

  def path_length(self) -> torch.Tensor:
    return self._path_len[self.levels, self.types]

  def project(self, pts_xy: torch.Tensor) -> Projection:
    """Project world points [B, K, 2] onto each env's centreline."""
    return project_points(self.path()[..., :2], pts_xy)

  def support_half_width(self, arc: torch.Tensor) -> torch.Tensor:
    """[B, K] half width of the walkable surface at ``arc``: the beam's, or a
    platform's where the arc lies on one."""
    beam = self.beam_arc()
    on_beam = (arc >= beam[:, :1]) & (arc <= beam[:, 1:])
    half_beam = (0.5 * self.width())[:, None].expand_as(arc)
    return torch.where(on_beam, half_beam, torch.full_like(arc, 0.5 * self.platform_width))
